#!/usr/bin/env python3
"""Rebuild assets/post-links.js: for every post, the other posts it links to.

Post pages use it (through assets/posts.js) to list "本文引用" and "引用本文".
Run from the repo root after adding a post or changing links between posts:

    python3 scripts/post-links.py
"""
import json
import hashlib
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
links = {}
for page in sorted((root / 'posts').glob('*/index.html')):
    slug = page.parent.name
    html = page.read_text(encoding='utf-8')
    # Ignore series navs (filled in by JS) and the 参考 list; count real in-text links.
    targets = re.findall(r'href="/posts/([a-z0-9-]+)/?[^"]*"', html)
    links[slug] = sorted({t for t in targets if t != slug and (root / 'posts' / t).is_dir()})

body = json.dumps(links, ensure_ascii=False, indent=1)
(root / 'assets' / 'post-links.js').write_text(
    '// Generated by scripts/post-links.py — do not edit by hand.\n'
    'window.POST_LINKS = ' + body + ';\n', encoding='utf-8')
print(sum(len(v) for v in links.values()), 'links across', len(links), 'posts')

# GitHub Pages caches assets independently from HTML. A new catalog or lesson
# must load matching data, styles and figure behavior.
def version_assets(page, names):
    html = page.read_text(encoding='utf-8')
    for name in names:
        version = hashlib.sha256((root / 'assets' / name).read_bytes()).hexdigest()[:12]
        html = re.sub(
            r'(/assets/' + re.escape(name) + r')(?:\?[^"\s]*)?(?=")',
            lambda match: match.group(1) + '?v=' + version,
            html,
        )
    page.write_text(html, encoding='utf-8')


shared = ('site.css', 'posts.js', 'series.js', 'post-links.js', 'curriculum.js',
          'curriculum.css', 'reader-math.js', 'reader-math.css', 'article.css',
          'article-steps.js', 'anim.js')
for page in sorted(root.rglob('*.html')):
    if '.git' not in page.parts and 'vendor' not in page.parts:
        version_assets(page, shared)
