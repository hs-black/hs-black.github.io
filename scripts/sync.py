#!/usr/bin/env python3
"""Sync generated metadata, asset versions, SEO tags, and verify links on hs-black.github.io.

Run from the repo root after adding/editing posts or shared assets:

    python3 scripts/sync.py           # sync post-links.js, sitemap.xml, robots.txt, OG tags, asset versions & check
    python3 scripts/sync.py --check   # verify only (no file writes)
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import math
import pathlib
import re
import sys

SITE = "https://hs-black.github.io"
SITE_NAME = "Zunzhe Zhang"
OG_IMAGE = f"{SITE}/assets/img/avatar.jpg"
ROOT = pathlib.Path(__file__).resolve().parent.parent

SHARED_ASSETS = (
    "site.css",
    "posts.js",
    "series.js",
    "post-links.js",
    "curriculum.js",
    "curriculum.css",
    "reader-math.js",
    "reader-math.css",
    "article.css",
    "article-steps.js",
    "anim.js",
    "encrypted-post.css",
    "encrypted-post.js",
)


def parse_posts_js() -> list[dict]:
    text = (ROOT / "assets" / "posts.js").read_text(encoding="utf-8")
    m = re.search(r"const POSTS = \[(.*?)\n  \];", text, re.S)
    if not m:
        raise RuntimeError("Could not locate POSTS array in assets/posts.js")
    entries: list[dict] = []
    for line in m.group(1).splitlines():
        s = line.strip().rstrip(",")
        if not s or s.startswith("//"):
            continue
        if s.startswith("{") and s.endswith("}"):
            entries.append(json.loads(s))
    if not entries:
        raise RuntimeError("Parsed 0 entries from POSTS in assets/posts.js")
    return entries


def parse_series_js() -> dict[str, dict]:
    text = (ROOT / "assets" / "series.js").read_text(encoding="utf-8")
    m = re.search(r"const SERIES = \{(.*?)\n  \};", text, re.S)
    if not m:
        raise RuntimeError("Could not locate SERIES object in assets/series.js")
    series: dict[str, dict] = {}
    for sm in re.finditer(
        r"""(\w+):\s*\{\s*title:\s*(['"])(.*?)\2,\s*posts:\s*\[(.*?)\],?\s*\}""",
        m.group(1),
        re.S,
    ):
        sid, title, body = sm.group(1), sm.group(3), sm.group(4)
        posts = []
        for pm in re.finditer(
            r"""\[\s*(['"])([^'"]+)\1\s*,\s*(['"])(.*?)\3\s*\]""",
            body,
            re.S,
        ):
            posts.append((pm.group(2), pm.group(4)))
        series[sid] = {"title": title, "posts": posts}
    return series


def is_encrypted_or_noindex(doc: str) -> bool:
    return (
        'id="encrypted-post-payload"' in doc
        or bool(re.search(r'<meta\s+name="robots"\s+content="[^"]*noindex', doc, re.I))
    )


def strip_html(doc: str) -> str:
    doc = re.sub(r"<script[\s\S]*?</script>", " ", doc)
    doc = re.sub(r"<style[\s\S]*?</style>", " ", doc)
    doc = re.sub(r"<svg[\s\S]*?</svg>", " ", doc)
    doc = re.sub(r"<[^>]+>", " ", doc)
    return re.sub(r"\s+", " ", html.unescape(doc)).strip()


def post_stats(doc: str) -> dict:
    article_m = re.search(r'<article\s+class="prose"[\s\S]*?</article>', doc)
    plain = strip_html(article_m.group(0) if article_m else doc)
    cjk = len(re.findall(r"[\u4e00-\u9fff]", plain))
    words = len(re.findall(r"[A-Za-z0-9_]+", plain))
    mins = max(2, math.ceil(cjk / 420 + words / 220))
    return {"mins": mins}


def build_post_links_and_meta(posts: list[dict]) -> tuple[dict[str, list[str]], dict[str, dict]]:
    encrypted_slugs = {p["slug"] for p in posts if p.get("kind") == "encrypted"}
    links: dict[str, list[str]] = {}
    meta: dict[str, dict] = {}
    for page in sorted((ROOT / "posts").glob("*/index.html")):
        slug = page.parent.name
        doc = page.read_text(encoding="utf-8")
        if slug in encrypted_slugs or is_encrypted_or_noindex(doc):
            links[slug] = []
            continue
        targets = re.findall(r'href="/posts/([a-z0-9-]+)/?[^"]*"', doc)
        links[slug] = sorted({t for t in targets if t != slug and (ROOT / "posts" / t).is_dir()})
        meta[slug] = post_stats(doc)
    return links, meta


def render_post_links_js(links: dict[str, list[str]], meta: dict[str, dict]) -> str:
    return (
        "// Generated by scripts/post-links.py — do not edit by hand.\n"
        "window.POST_LINKS = " + json.dumps(links, ensure_ascii=False, indent=1) + ";\n"
        "window.POST_META = " + json.dumps(meta, ensure_ascii=False, indent=1) + ";\n"
    )


def public_pages(posts: list[dict]) -> list[tuple[pathlib.Path, str, str, str]]:
    """Return list of (file_path, url_path, og_type, lastmod) excluding encrypted/noindex pages."""
    latest = max((p["date"] for p in posts), default="2026-11-11")
    pages = [
        (ROOT / "index.html", "/", "website", latest),
        (ROOT / "papers" / "index.html", "/papers/", "website", latest),
        (ROOT / "blog" / "index.html", "/blog/", "website", latest),
        (ROOT / "tools" / "index.html", "/tools/", "website", latest),
    ]
    for tool in sorted((ROOT / "tools").glob("*/index.html")):
        pages.append((tool, f"/tools/{tool.parent.name}/", "website", latest))
    by_slug = {p["slug"]: p for p in posts}
    for post_page in sorted((ROOT / "posts").glob("*/index.html")):
        slug = post_page.parent.name
        entry = by_slug.get(slug, {})
        if entry.get("kind") == "encrypted":
            continue
        doc = post_page.read_text(encoding="utf-8")
        if is_encrypted_or_noindex(doc):
            continue
        lastmod = entry.get("date", latest)
        pages.append((post_page, f"/posts/{slug}/", "article", lastmod))
    return pages


def render_sitemap_xml(pages: list[tuple[pathlib.Path, str, str, str]]) -> str:
    urls = []
    for _, url_path, _, lastmod in pages:
        urls.append(
            "  <url>\n"
            f"    <loc>{SITE}{url_path}</loc>\n"
            f"    <lastmod>{lastmod}</lastmod>\n"
            "  </url>"
        )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    )


def sync_og_tags(page: pathlib.Path, url_path: str, og_type: str) -> str | None:
    doc = page.read_text(encoding="utf-8")
    tm = re.search(r"<title>(.*?)</title>", doc, re.S)
    dm = re.search(r'<meta\s+name="description"\s+content="([^"]*)"\s*/?>', doc)
    if not tm or not dm:
        return None
    title = tm.group(1).strip()
    desc = dm.group(1).strip()
    url = f"{SITE}{url_path}"
    block = (
        f'  <link rel="canonical" href="{url}">\n'
        f'  <meta property="og:site_name" content="{SITE_NAME}">\n'
        f'  <meta property="og:type" content="{og_type}">\n'
        f'  <meta property="og:title" content="{title}">\n'
        f'  <meta property="og:description" content="{desc}">\n'
        f'  <meta property="og:url" content="{url}">\n'
        f'  <meta property="og:image" content="{OG_IMAGE}">\n'
        f'  <meta name="twitter:card" content="summary">'
    )
    cleaned = re.sub(
        r'\n?[ \t]*<link\s+rel="canonical"[^>]*>'
        r'|\n?[ \t]*<meta\s+property="og:[^"]*"[^>]*>'
        r'|\n?[ \t]*<meta\s+name="twitter:card"[^>]*>',
        "",
        doc,
    )
    anchor = re.search(r'([ \t]*<meta\s+name="description"\s+content="[^"]*"\s*/?>)', cleaned)
    if not anchor:
        return None
    updated = cleaned[: anchor.end()] + "\n" + block + cleaned[anchor.end() :]
    return updated if updated != doc else None


def version_assets_all() -> int:
    versions = {
        name: hashlib.sha256((ROOT / "assets" / name).read_bytes()).hexdigest()[:12]
        for name in SHARED_ASSETS
        if (ROOT / "assets" / name).is_file()
    }
    changed = 0
    for page in sorted(ROOT.rglob("*.html")):
        if {".git", "vendor", "drafts"}.intersection(page.relative_to(ROOT).parts):
            continue
        doc = page.read_text(encoding="utf-8")
        new_doc = doc
        for name, ver in versions.items():
            new_doc = re.sub(
                r"(/assets/" + re.escape(name) + r')(?:\?[^"\s]*)?(?=")',
                lambda m, v=ver: m.group(1) + "?v=" + v,
                new_doc,
            )
        if new_doc != doc:
            page.write_text(new_doc, encoding="utf-8")
            changed += 1
    return changed


def verify(posts: list[dict], series: dict[str, dict]) -> list[str]:
    errors: list[str] = []
    disk_slugs = {p.parent.name for p in (ROOT / "posts").glob("*/index.html")}
    js_slugs = {p["slug"] for p in posts}
    by_slug = {p["slug"]: p for p in posts}

    for s in sorted(disk_slugs - js_slugs):
        errors.append(f"Post folder posts/{s}/ is missing from assets/posts.js")
    for s in sorted(js_slugs - disk_slugs):
        errors.append(f"Entry '{s}' in assets/posts.js has no posts/{s}/index.html")

    # Verify feed.xml covers every post in assets/posts.js.
    feed_text = (ROOT / "feed.xml").read_text(encoding="utf-8")
    feed_slugs = set(re.findall(r"<link>https://hs-black\.github\.io/posts/([a-z0-9-]+)/</link>", feed_text))
    for s in sorted(js_slugs - feed_slugs):
        errors.append(f"Post '{s}' is in assets/posts.js but missing from feed.xml")
    for s in sorted(feed_slugs - js_slugs):
        errors.append(f"Post '{s}' is in feed.xml but missing from assets/posts.js")

    post_ids: dict[str, set[str]] = {}
    post_h1: dict[str, str] = {}
    for slug in sorted(disk_slugs):
        page = ROOT / "posts" / slug / "index.html"
        doc = page.read_text(encoding="utf-8")
        post_ids[slug] = set(re.findall(r'\bid="([^"]+)"', doc))
        h1m = re.search(r"<h1[^>]*>(.*?)</h1>", doc, re.S)
        post_h1[slug] = re.sub(r"<[^>]+>", "", h1m.group(1)).strip() if h1m else ""
        if by_slug.get(slug, {}).get("kind") != "encrypted":
            if "/assets/posts.js" not in doc:
                errors.append(f"posts/{slug}/index.html does not load /assets/posts.js")
            if "/assets/post-links.js" not in doc:
                errors.append(f"posts/{slug}/index.html does not load /assets/post-links.js")

    # Curriculum stages are rendered dynamically on /posts/llm-engineering/.
    curr = ROOT / "assets" / "curriculum.js"
    if curr.is_file() and "llm-engineering" in post_ids:
        post_ids["llm-engineering"].update(re.findall(r"\bid:\s*'([^']+)'", curr.read_text(encoding="utf-8")))

    for sid, sdata in series.items():
        for slug, title in sdata["posts"]:
            if slug not in disk_slugs:
                errors.append(f"series '{sid}' references missing post '{slug}'")
            elif slug not in js_slugs:
                errors.append(f"series '{sid}' references '{slug}' not in assets/posts.js")
            elif post_h1.get(slug) and post_h1[slug] != title:
                errors.append(f"series '{sid}' title mismatch for '{slug}': '{title}' vs <h1> '{post_h1[slug]}'")

    html_files = [
        ROOT / "index.html",
        ROOT / "papers" / "index.html",
        ROOT / "blog" / "index.html",
        ROOT / "tools" / "index.html",
        ROOT / "404.html",
        *sorted((ROOT / "tools").glob("*/index.html")),
        *sorted((ROOT / "posts").glob("*/index.html")),
    ]
    for hf in html_files:
        doc = hf.read_text(encoding="utf-8")
        if is_encrypted_or_noindex(doc):
            continue
        rel = hf.relative_to(ROOT)
        for m in re.finditer(r'href="/posts/([a-z0-9-]+)/?(?:#([^"]*))?"', doc):
            slug, frag = m.group(1), m.group(2)
            if slug not in disk_slugs:
                errors.append(f"{rel}: broken link /posts/{slug}/")
                continue
            if frag and frag not in post_ids[slug]:
                errors.append(f"{rel}: broken anchor /posts/{slug}/#{frag}")

    return errors


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="Only verify, do not write files")
    args = ap.parse_args()

    posts = parse_posts_js()
    series = parse_series_js()
    links, meta = build_post_links_and_meta(posts)
    pages = public_pages(posts)

    if not args.check:
        (ROOT / "assets" / "post-links.js").write_text(render_post_links_js(links, meta), encoding="utf-8")
        (ROOT / "sitemap.xml").write_text(render_sitemap_xml(pages), encoding="utf-8")
        (ROOT / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n", encoding="utf-8")
        og_updated = 0
        for page, url_path, og_type, _ in pages:
            new_doc = sync_og_tags(page, url_path, og_type)
            if new_doc is not None:
                page.write_text(new_doc, encoding="utf-8")
                og_updated += 1
        versioned = version_assets_all()
        print(
            f"Synced {sum(len(v) for v in links.values())} cross-links across {len(links)} posts, "
            f"sitemap.xml ({len(pages)} URLs), OG tags ({og_updated} updated), "
            f"versioned assets ({versioned} HTML files)."
        )

    errors = verify(posts, series)
    if errors:
        print("ERRORS found:", file=sys.stderr)
        for e in errors:
            print("  -", e, file=sys.stderr)
        return 1
    print(f"Checks passed: {len(posts)} posts, {len(series)} series, feed.xml & all links valid.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
